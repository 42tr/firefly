import assert from 'node:assert/strict'
import test from 'node:test'
import { createRenderer, markRaw, nextTick } from 'vue'
import { useMessageScroll } from './useMessageScroll.js'

async function mount(t) {
  let unmount = () => {}
  const originals = new Map(['requestAnimationFrame', 'cancelAnimationFrame', 'ResizeObserver', 'matchMedia']
    .map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]))
  t.after(() => {
    unmount()
    for (const [key, descriptor] of originals) {
      if (descriptor) Object.defineProperty(globalThis, key, descriptor)
      else delete globalThis[key]
    }
  })
  let id = 0, resize, model
  const frames = new Map(), listeners = new Map(), writes = []
  globalThis.requestAnimationFrame = callback => { frames.set(++id, callback); return id }
  globalThis.cancelAnimationFrame = id => frames.delete(id)
  globalThis.ResizeObserver = class { constructor(callback) { resize = callback } observe() {} disconnect() {} }
  globalThis.matchMedia = () => ({ matches: false })
  let top = 0
  const panel = markRaw({ scrollHeight: 200, clientHeight: 100, clientWidth: 400, clientLeft: 0,
    firstElementChild: {}, style: {},
    get scrollTop() { return top },
    set scrollTop(value) { top = Math.round(Math.min(Math.max(0, value), this.scrollHeight - this.clientHeight)); writes.push(top) },
    addEventListener: (name, handler) => listeners.set(name, handler),
    removeEventListener: name => listeners.delete(name),
    getBoundingClientRect: () => ({ left: 0, top: 0, bottom: 100 }),
  })
  const renderer = createRenderer({ createComment: () => ({}), insert() {}, remove() {}, parentNode() {}, nextSibling() {} })
  const app = renderer.createApp({ setup() { model = useMessageScroll(); return () => null } })
  app.mount({})
  let mounted = true
  unmount = () => { if (mounted) { app.unmount(); mounted = false } }
  model.chatPanel.value = panel
  await nextTick()
  return { model, panel, frames, writes, resize: () => resize(), listeners,
    frame(time) { const pending = [...frames.values()]; frames.clear(); pending.forEach(callback => callback(time)) },
    scroll(value) { top = value; listeners.get('scroll')() }, unmount }
}

test('deltas and resizes share one animation that follows the latest bottom', async t => {
  const view = await mount(t)
  for (let i = 0; i < 20; i++) { await view.model.scrollToBottom(); view.resize() }
  assert.equal(view.frames.size, 1)
  assert.equal(view.writes.length, 0)
  view.frame(16)
  assert.ok(view.panel.scrollTop > 0 && view.panel.scrollTop < 100)
  // Native scroll events generated by our writes must not release follow mode.
  view.listeners.get('scroll')()
  assert.equal(view.model.isPinnedToBottom.value, true)
  view.panel.scrollHeight = 250
  view.resize()
  assert.equal(view.frames.size, 1)
  for (let time = 32; time < 500 && view.frames.size; time += 16) view.frame(time)
  assert.ok(150 - view.panel.scrollTop <= 1)
  assert.equal(view.frames.size, 0)
})

test('upward user input cancels follow immediately, including within the bottom threshold', async t => {
  const view = await mount(t)
  await view.model.scrollToBottom({ force: true })
  view.panel.scrollHeight = 240
  view.resize()
  view.listeners.get('wheel')({ deltaY: -10 })
  view.scroll(90)
  assert.equal(view.model.isPinnedToBottom.value, false)
  assert.equal(view.frames.size, 0)
  assert.equal(view.panel.style.overflowAnchor, '')
  const writes = view.writes.length
  view.panel.scrollHeight = 500
  await view.model.scrollToBottom()
  view.resize()
  assert.equal(view.writes.length, writes)
  assert.equal(view.frames.size, 0)
  // Downward user scrolling near the bottom opts back in.
  view.scroll(380)
  assert.equal(view.model.isPinnedToBottom.value, true)
  assert.equal(view.frames.size, 1)
})

test('forced positioning is immediate; reduced motion skips interpolation and unmount removes work', async t => {
  const view = await mount(t)
  await view.model.scrollToBottom({ force: true })
  assert.equal(view.panel.scrollTop, 100)
  assert.equal(view.frames.size, 0)
  globalThis.matchMedia = () => ({ matches: true })
  view.panel.scrollHeight = 300
  view.resize()
  view.frame(16)
  assert.equal(view.panel.scrollTop, 200)
  assert.equal(view.frames.size, 0)
  view.panel.scrollHeight = 400
  view.resize()
  view.unmount()
  assert.equal(view.frames.size, 0)
  assert.equal(view.listeners.size, 0)
})

test('touch and keyboard release follow while editing and ordinary panel clicks preserve it', async t => {
  const view = await mount(t)
  view.listeners.get('pointerdown')({ target: view.panel, clientX: 20 })
  assert.equal(view.model.isPinnedToBottom.value, true)
  view.listeners.get('keydown')({ key: 'ArrowUp', target: { closest: () => ({}) } })
  assert.equal(view.model.isPinnedToBottom.value, true)
  view.listeners.get('touchstart')({ touches: [{ clientY: 100 }] })
  view.listeners.get('touchmove')({ touches: [{ clientY: 130 }] })
  assert.equal(view.model.isPinnedToBottom.value, false)
  await view.model.scrollToBottom({ force: true })
  view.listeners.get('keydown')({ key: 'PageUp' })
  assert.equal(view.model.isPinnedToBottom.value, false)
  assert.equal(view.frames.size, 0)
})

async function replaceLongReply(t) {
  const view = await mount(t)
  let naturalHeight = 600
  const element = { style: {}, get offsetHeight() { return Math.max(naturalHeight, parseFloat(this.style.minHeight) || 0) } }
  const body = { getBoundingClientRect: () => ({
    top: 400 + element.offsetHeight - naturalHeight - view.panel.scrollTop,
    bottom: 400 + element.offsetHeight - view.panel.scrollTop,
  }) }
  view.panel.querySelectorAll = () => [body]
  Object.defineProperty(view.panel, 'scrollHeight', { get: () => 400 + element.offsetHeight })
  await view.model.scrollToBottom({ force: true })
  view.model.vStableReply.beforeUpdate(element, { value: {}, oldValue: {} })
  naturalHeight = 40
  return { ...view, element, body }
}

test('a shorter replacement preserves the scroll range and deliberate scrolling reclaims space without moving its content', async t => {
  const view = await replaceLongReply(t)
  assert.equal(view.panel.scrollHeight, 1000)
  assert.equal(view.panel.scrollTop, 900)
  const before = view.body.getBoundingClientRect().top
  view.listeners.get('wheel')({ deltaY: -10 })
  assert.equal(view.element.style.minHeight, '')
  assert.equal(view.panel.scrollHeight, 440)
  assert.equal(view.panel.scrollTop, 340)
  assert.equal(view.body.getBoundingClientRect().top, before)
  assert.equal(view.model.isPinnedToBottom.value, false)
})

test('a new turn or an explicit return to the bottom releases reserved reply space', async t => {
  const view = await replaceLongReply(t)
  view.model.vStableReply.mounted({}, { value: {} })
  assert.equal(view.element.style.minHeight, '')
  assert.equal(view.panel.scrollTop, 340)
  assert.equal(view.model.isPinnedToBottom.value, true)
  view.model.vStableReply.beforeUpdate(view.element, { value: {}, oldValue: {} })
  await view.model.scrollToBottom({ force: true })
  assert.equal(view.element.style.minHeight, '')
  assert.equal(view.panel.scrollTop, 340)
})
